const shaderString = [
  "struct Uniforms {",
  "  time: f32,",
  "  micLevel: f32,",
  "  stateListen: f32,",
  "  listenTimestamp: f32,",
  "  stateThink: f32,",
  "  thinkTimestamp: f32,",
  "  stateSpeak: f32,",
  "  speakTimestamp: f32,",
  "  avgMag: vec4f,",
  "  cumulativeAudio: vec4f,",
  "  viewport: vec2f,",
  "  watercolorStrength: f32,",
  "  watercolorAnimated: f32,",
  "  bloopColorMain: vec4f,",
  "  bloopColorLow: vec4f,",
  "  bloopColorMid: vec4f,",
  "  bloopColorHigh: vec4f,",
  "};",
  "",
  "@group(0) @binding(0) var<uniform> ubo: Uniforms;",
  "",
  "@fragment",
  "fn fs_main(@location(0) uv: vec2f) -> @location(0) vec4f {",
  "  let center = vec2f(0.5, 0.5);",
  "  let p = uv - center;",
  "  let dist = length(p);",
  "  let pulse = sin(ubo.time * 2.8 + ubo.cumulativeAudio.x * 2.0) * 0.04 * (1.0 + ubo.micLevel * 3.0);",
  "  let baseRadius = 0.35 + pulse;",
  "  let angle = atan2(p.y, p.x);",
  "  let wave = sin(angle * 5.0 + ubo.time * 3.5) * 0.03 * (1.0 + ubo.avgMag.y * 3.0);",
  "  let r = dist + wave;",
  "  if (r > 0.48) { return vec4f(0.0, 0.0, 0.0, 0.0); }",
  "  let edge = smoothstep(baseRadius + 0.12, baseRadius - 0.06, r);",
  "  let core = smoothstep(baseRadius - 0.05, 0.0, r);",
  "  var col = mix(ubo.bloopColorLow.rgb, ubo.bloopColorMain.rgb, core);",
  "  col = mix(col, ubo.bloopColorHigh.rgb, pow(core, 2.0) * 0.75);",
  "  let alpha = edge * (0.95 + ubo.micLevel * 0.05);",
  "  return vec4f(col * alpha, alpha);",
  "}",
].join("\n");

export const BLOOP_WGSL = shaderString;
